// Rate limiting
const rateLimitMap = new Map();
const RATE_LIMIT_WINDOW = 60 * 1000;
const MAX_REQUESTS = 15;

function isRateLimited(ip) {
  const now = Date.now();
  const r = rateLimitMap.get(ip);
  if (!r || now - r.start > RATE_LIMIT_WINDOW) {
    rateLimitMap.set(ip, { start: now, count: 1 });
    return false;
  }
  if (r.count >= MAX_REQUESTS) return true;
  r.count++;
  return false;
}

export async function POST(request) {
  try {
    const ip = request.headers.get('x-forwarded-for') || 'unknown';
    if (isRateLimited(ip)) {
      return Response.json({ error: 'Too many requests. Please wait a moment.' }, { status: 429 });
    }

    const { messages, childProfiles, momProfile } = await request.json();
    if (!messages || !Array.isArray(messages) || messages.length === 0) {
      return Response.json({ error: 'Messages are required.' }, { status: 400 });
    }

    let system = SYSTEM_PROMPT;

    // Add mom's profile info
    if (momProfile) {
      system += `\n\n## ABOUT THIS MOM\n`;
      if (momProfile.momName) system += `- Her name is ${momProfile.momName}. Use her name naturally in conversation to make it personal and warm.\n`;
      if (momProfile.momAge) system += `- Age range: ${momProfile.momAge}\n`;
      if (momProfile.country) system += `- Lives in: ${momProfile.country}. Be mindful of regional context when giving suggestions.\n`;
      if (momProfile.parentingStyle) {
        const styleLabels = { 'gentle': 'Gentle & Conscious parenting', 'structured': 'Structured routines & clear boundaries', 'balanced': 'A balanced mix of gentle and structured', 'instinctive': 'Instinct-led, go-with-the-flow', 'figuring-out': 'Still exploring what works for her' };
        system += `- Parenting approach: ${styleLabels[momProfile.parentingStyle] || momProfile.parentingStyle}. Match your advice to this style — don't suggest approaches that clash with her values.\n`;
      }
      if (momProfile.challenges && momProfile.challenges.length > 0) {
        const challengeLabels = { 'sleep': 'sleep struggles', 'tantrums': 'tantrums/behavior', 'feeding': 'feeding/picky eating', 'guilt': 'mom guilt', 'work-life': 'work-life balance', 'loneliness': 'loneliness/isolation', 'anxiety': 'anxiety/overwhelm', 'partner': 'partner dynamics', 'screen-time': 'screen time', 'milestones': 'developmental worries', 'discipline': 'setting boundaries', 'self-care': 'finding me-time' };
        system += `- Current biggest challenges: ${momProfile.challenges.map(c => challengeLabels[c] || c).join(', ')}. Be especially supportive and proactive about these topics.\n`;
      }
      if (momProfile.supportSystem) {
        const supportLabels = { 'partner-home': 'Has a partner at home who shares the load', 'partner-busy': 'Has a partner but they are often busy/away — she handles a lot alone', 'family-nearby': 'Has family nearby for support', 'family-far': 'Family lives far away — support is mostly virtual', 'solo': 'Solo parent — doing it all on her own', 'community': 'Relies on friends and community for support', 'mixed': 'Mixed/varies — support comes and goes' };
        system += `- Support situation: ${supportLabels[momProfile.supportSystem] || momProfile.supportSystem}. IMPORTANT: Tailor advice to be realistic for her situation. For example, do NOT suggest "ask your partner to help" if she is a solo parent. Do NOT suggest "drop the kids at grandma's" if family is far away.\n`;
      }
    }

    if (childProfiles && childProfiles.length > 0) {
      const info = childProfiles.map(c =>
        `- ${c.name}, age: ${c.age}${c.notes ? ` (${c.notes})` : ''}`
      ).join('\n');
      system += `\n## THIS MOM'S CHILDREN\nAlways reference by name and tailor advice to their ages:\n${info}`;
    }

    const apiKey = process.env.ANTHROPIC_API_KEY;
    if (!apiKey) {
      return Response.json({ error: 'Server configuration error.' }, { status: 500 });
    }

    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: 'claude-sonnet-4-20250514',
        max_tokens: 1024,
        system,
        messages: messages.slice(-20).map(m => ({ role: m.role, content: m.content })),
      }),
    });

    if (!response.ok) {
      return Response.json({ error: 'Failed to get AI response.' }, { status: 502 });
    }

    return Response.json(await response.json());
  } catch (error) {
    console.error('Chat API error:', error);
    return Response.json({ error: 'Internal server error.' }, { status: 500 });
  }
}
